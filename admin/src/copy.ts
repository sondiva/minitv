export type Locale = "zh" | "vi";

const KEY = "minitv_admin_locale";

let current: Locale = loadLocale();

export function loadLocale(): Locale {
  try {
    return window.localStorage.getItem(KEY) === "zh" ? "zh" : "vi";
  } catch {
    return "vi";
  }
}

export function getLocale(): Locale {
  return current;
}

type LocaleListener = (locale: Locale) => void;
const listeners = new Set<LocaleListener>();

export function subscribeLocale(fn: LocaleListener): () => void {
  listeners.add(fn);
  return () => {
    listeners.delete(fn);
  };
}

export function setLocale(locale: Locale): void {
  current = locale;
  try {
    window.localStorage.setItem(KEY, locale);
  } catch {
    /* private mode: the choice is nice-to-have, the UI still switches */
  }
  for (const fn of listeners) fn(locale);
}

export function t(key: string, vars: Record<string, string | number> = {}): string {
  const table = current === "vi" ? vi : zh;
  let text = table[key] ?? zh[key] ?? key;
  for (const [name, value] of Object.entries(vars)) {
    text = text.split(`{${name}}`).join(String(value));
  }
  return text;
}
